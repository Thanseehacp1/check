/* eslint-disable react-native/no-inline-styles */
import React, {useState, useContext} from 'react';
import {
  View,
  Text,
  Image,
  TouchableOpacity,
  StyleSheet,
  SafeAreaView,
} from 'react-native';
import {useSafeAreaInsets} from 'react-native-safe-area-context';
import Icon1 from 'react-native-vector-icons/Feather';
import {useNavigation} from '@react-navigation/native';
import {NativeStackNavigationProp} from '@react-navigation/native-stack';
import {MainStackParamList} from '../stacks/MainStack';
import LinearGradient from 'react-native-linear-gradient';
import {ThemeContext} from '../components/ThemeContext'; // Import ThemeContext
import { moderateScale } from 'react-native-size-matters';
import { heightPercentageToDP } from 'react-native-responsive-screen';
import { RFValue } from 'react-native-responsive-fontsize';

const onboardingData = [
  {
    id: '1',
    title: 'Smart Legal Practice Starts Here',
    description:
      'Save hours every week with intelligent case tracking, reminders, and updates—built for busy lawyers',
    image: require('../assets/one.png'),
  },
  {
    id: '2',
    title: 'Stay Ahead, Stay Informed',
    description:
      'Get instant access to cause lists, orders, and past judgements—organized and accessible in one tap',
    image: require('../assets/two.png'),
  },
  {
    id: '3',
    title: 'Seamless Client Communication',
    description:
      'Notify clients with full or summarized case proceedings via Email, WhatsApp, or PDF—auto-generated by AI',
    image: require('../assets/three.png'),
  },
  {
    id: '4',
    title: 'Your Digital Legal Assistant',
    description:
      'From reminders to drafting summaries, let our automation take care of the repetitive work so you can focus on winning cases',
    image: require('../assets/four.png'),
  },
];

type StartScreenNavigationProp = NativeStackNavigationProp<
  MainStackParamList,
  'StartScreen'
>;

const StartScreen = () => {
  const {colors} = useContext(ThemeContext);
  const navigation = useNavigation<StartScreenNavigationProp>();
  const [currentIndex, setCurrentIndex] = useState(0);
  const insets = useSafeAreaInsets();

  
  // const handleNext = () => {
  //   if (currentIndex < onboardingData.length - 1) {
  //     setCurrentIndex(currentIndex + 1);
  //   }

  const handleNext = () => {
    if (currentIndex < onboardingData.length - 1) {
      setCurrentIndex(currentIndex + 1);
    } else {
      navigation.navigate('LoginScreen');
    }
  };

  const handleSkip = () => {
     // setCurrentIndex(onboardingData.length - 1);
    navigation.navigate('LoginScreen');
  };

  const item = onboardingData[currentIndex];

  const styles = StyleSheet.create({
    container: {
      flex: 1,
      backgroundColor: colors.background,
      paddingTop: insets.top,
    },
    header: {
      flexDirection: 'row',
      justifyContent: 'space-between',
      alignItems: 'center',
      paddingHorizontal: moderateScale(22),
      paddingVertical: moderateScale(8),
      marginTop: moderateScale(8),
    },
    backButton: {
      width : moderateScale(40),height:moderateScale(40),
      borderRadius: heightPercentageToDP('25%'),
      borderWidth: moderateScale(1),
      borderColor: colors.border,
      justifyContent: 'center',
      alignItems: 'center',
    },
    skipText: {
      color: colors.text,
      fontSize: moderateScale(14),
    },
    contentContainer: {
      flex: 1,
      justifyContent: 'center',
      alignItems: 'center',
      paddingHorizontal: moderateScale(22),
      paddingBottom: moderateScale(36),
    },
    image: {
      width: '100%',
      height: 280,
      resizeMode: 'contain',
    },
    title: {
      color: colors.text,
      fontSize: RFValue(15),
      marginTop: moderateScale(72),
      fontWeight: 'bold',
      textAlign: 'center',
    },
    description: {
      color: colors.secondaryText,
      marginTop: moderateScale(8),
      textAlign: 'center',
      fontSize: RFValue(10.5),
    },
    bottomContainer: {
      paddingHorizontal: moderateScale(22),
      paddingBottom: moderateScale(22),
    },
    progressContainer: {
      paddingHorizontal: moderateScale(22),
      paddingBottom: moderateScale(22),
    },
    progressDotsContainer: {
      flexDirection: 'row',
      justifyContent: 'center',
      gap: moderateScale(8),
    },
    progressDotActive: {
      height: moderateScale(4),
      marginBottom: moderateScale(36),
      borderRadius: moderateScale(2),
      width: moderateScale(56),
    },
    progressDotInactive: {
      height: moderateScale(4),
      marginBottom: moderateScale(36),
      borderRadius: moderateScale(2),
      backgroundColor: colors.disabled,
      width: moderateScale(56),
    },
    nextButton: {
      borderRadius: moderateScale(12),
      overflow: 'hidden',
    },
    nextButtonGradient: {
      paddingVertical: moderateScale(12),
      borderRadius: moderateScale(12),
    },
    nextButtonText: {
      textAlign: 'center',
      color: colors.textOnGradient,
      fontWeight: '600',
      fontSize: RFValue(14),
    },
  });

  return (
    <SafeAreaView style={styles.container}>
      <View style={styles.header}>
        {currentIndex > 0 ? (
          <TouchableOpacity
            onPress={() => setCurrentIndex(prev => Math.max(prev - 1, 0))}
            style={styles.backButton}>
            <Icon1 name="arrow-left" size={heightPercentageToDP('2.5%')} color={colors.primary} />
          </TouchableOpacity>
        ) : (
          <View style={{width: 40}} />
        )}
        <Text style={styles.skipText} onPress={handleSkip}>
          Skip
        </Text>
      </View>

      <View style={styles.contentContainer}>
        <Image source={item.image} style={styles.image} />
        <Text style={styles.title}>{item.title}</Text>
        <Text style={styles.description}>{item.description}</Text>
      </View>

      <View style={styles.bottomContainer}>
        <View style={styles.progressContainer}>
          <View style={styles.progressDotsContainer}>
            {onboardingData.map((_, index) => {
              if (index === currentIndex) {
                return (
                  <LinearGradient
                    key={index}
                    colors={colors.buttonGradient}
                    start={{x: 0, y: 0}}
                    end={{x: 1, y: 0}}
                    style={styles.progressDotActive}
                  />
                );
              } else {
                return (
                  <View key={index} style={styles.progressDotInactive} />
                );
              }
            })}
          </View>
        </View>
        <TouchableOpacity onPress={handleNext} style={styles.nextButton}>
          <LinearGradient
            colors={colors.buttonGradient}
            start={{x: 0, y: 0}}
            end={{x: 1, y: 1}}
            style={styles.nextButtonGradient}>
            <Text style={styles.nextButtonText}>
              {currentIndex === onboardingData.length - 1
                ? 'Get Started'
                : 'Next'}
            </Text>
          </LinearGradient>
        </TouchableOpacity>
      </View>
    </SafeAreaView>
  );
};

export default StartScreen;